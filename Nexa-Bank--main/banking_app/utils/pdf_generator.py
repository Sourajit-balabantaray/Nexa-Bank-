"""
PDF Generator for NexaBank using ReportLab.
Generates transaction receipts and bank statements.
"""

import io
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm, mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
    HRFlowable
)
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from utils.time import utc_now


# Brand colors
NAVY = colors.HexColor('#0a1628')
BLUE = colors.HexColor('#3b82f6')
GREEN = colors.HexColor('#10b981')
RED = colors.HexColor('#ef4444')
LIGHT_GRAY = colors.HexColor('#f8fafc')
GRAY = colors.HexColor('#64748b')


def generate_receipt_pdf(transaction, account, user):
    """
    Generate a transaction receipt PDF.
    Returns bytes of the PDF.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2*cm,
        leftMargin=2*cm,
        topMargin=2*cm,
        bottomMargin=2*cm
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        'Title',
        parent=styles['Heading1'],
        fontSize=24,
        textColor=NAVY,
        alignment=TA_CENTER,
        spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        'Subtitle',
        parent=styles['Normal'],
        fontSize=11,
        textColor=GRAY,
        alignment=TA_CENTER,
        spaceAfter=20
    )
    label_style = ParagraphStyle(
        'Label',
        parent=styles['Normal'],
        fontSize=9,
        textColor=GRAY,
        spaceAfter=2
    )
    value_style = ParagraphStyle(
        'Value',
        parent=styles['Normal'],
        fontSize=11,
        textColor=NAVY,
        spaceAfter=8
    )
    success_style = ParagraphStyle(
        'Success',
        parent=styles['Normal'],
        fontSize=18,
        textColor=GREEN,
        alignment=TA_CENTER,
        spaceAfter=10
    )
    amount_style = ParagraphStyle(
        'Amount',
        parent=styles['Normal'],
        fontSize=28,
        textColor=NAVY,
        alignment=TA_CENTER,
        spaceAfter=6,
        fontName='Helvetica-Bold'
    )

    story = []

    # Header
    story.append(Paragraph("NexaBank", title_style))
    story.append(Paragraph("DEMO BANKING APPLICATION — NOT A REAL TRANSACTION", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=2, color=BLUE))
    story.append(Spacer(1, 0.5*cm))

    # Success banner
    story.append(Paragraph("✓ TRANSACTION SUCCESSFUL", success_style))
    story.append(Spacer(1, 0.3*cm))

    # Amount
    story.append(Paragraph(f"₹{transaction.amount:,.2f}", amount_style))
    story.append(Spacer(1, 0.5*cm))
    story.append(HRFlowable(width="100%", thickness=1, color=LIGHT_GRAY))
    story.append(Spacer(1, 0.5*cm))

    # Transaction details table
    details = [
        ['Transaction ID', transaction.transaction_id],
        ['Date & Time', transaction.created_at.strftime('%d %B %Y, %I:%M %p UTC')],
        ['Type', transaction.transaction_type.upper()],
        ['Category', transaction.category.title()],
        ['From', transaction.sender or user.full_name],
        ['To', transaction.receiver or user.full_name],
        ['Description', transaction.description or '—'],
        ['Status', transaction.status.upper()],
        ['Balance After', f"₹{transaction.balance_after:,.2f}" if transaction.balance_after else '—'],
    ]

    table = Table(details, colWidths=[5*cm, 12*cm])
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), LIGHT_GRAY),
        ('TEXTCOLOR', (0, 0), (0, -1), GRAY),
        ('TEXTCOLOR', (1, 0), (1, -1), NAVY),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('ROWBACKGROUNDS', (0, 0), (-1, -1), [colors.white, LIGHT_GRAY]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0, 0), (-1, -1), 8),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))

    story.append(table)
    story.append(Spacer(1, 1*cm))

    # Footer
    story.append(HRFlowable(width="100%", thickness=1, color=LIGHT_GRAY))
    story.append(Spacer(1, 0.3*cm))

    footer_style = ParagraphStyle(
        'Footer',
        parent=styles['Normal'],
        fontSize=8,
        textColor=GRAY,
        alignment=TA_CENTER,
    )
    story.append(Paragraph(
        f"Generated on {utc_now().strftime('%d %B %Y at %I:%M %p UTC')}",
        footer_style
    ))
    story.append(Paragraph(
        "⚠️ This is a DEMO receipt generated by NexaBank — a college project banking application. "
        "This does not represent a real financial transaction.",
        footer_style
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


def generate_statement_pdf(transactions, account, user, start_date, end_date):
    """
    Generate a bank statement PDF for a date range.
    Returns bytes of the PDF.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=1.5*cm,
        leftMargin=1.5*cm,
        topMargin=2*cm,
        bottomMargin=2*cm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'Title', parent=styles['Heading1'],
        fontSize=20, textColor=NAVY, alignment=TA_CENTER, spaceAfter=4
    )
    subtitle_style = ParagraphStyle(
        'Sub', parent=styles['Normal'],
        fontSize=10, textColor=GRAY, alignment=TA_CENTER, spaceAfter=16
    )
    normal_center = ParagraphStyle(
        'NC', parent=styles['Normal'],
        fontSize=10, alignment=TA_CENTER
    )

    story = []

    # Header
    story.append(Paragraph("NexaBank", title_style))
    story.append(Paragraph("Account Statement — DEMO APPLICATION", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=2, color=BLUE))
    story.append(Spacer(1, 0.4*cm))

    # Account info
    account_info = [
        ['Account Holder', user.full_name, 'Account Number', account.masked_number],
        ['Account Type', account.account_type.title(), 'IFSC Code', account.ifsc_code],
        ['Statement Period',
         f"{start_date.strftime('%d %b %Y')} — {end_date.strftime('%d %b %Y')}",
         'Current Balance', f"₹{account.balance:,.2f}"],
    ]

    info_table = Table(account_info, colWidths=[4*cm, 6*cm, 4*cm, 4*cm])
    info_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), LIGHT_GRAY),
        ('BACKGROUND', (2, 0), (2, -1), LIGHT_GRAY),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME', (2, 0), (2, -1), 'Helvetica-Bold'),
        ('TEXTCOLOR', (0, 0), (0, -1), GRAY),
        ('TEXTCOLOR', (2, 0), (2, -1), GRAY),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0, 0), (-1, -1), 7),
    ]))
    story.append(info_table)
    story.append(Spacer(1, 0.5*cm))

    # Transactions table
    headers = ['Date', 'Transaction ID', 'Description', 'Category', 'Type', 'Amount', 'Balance']
    table_data = [headers]

    total_credit = 0.0
    total_debit = 0.0

    for txn in transactions:
        amount_str = f"₹{txn.amount:,.2f}"
        if txn.transaction_type == 'credit':
            total_credit += txn.amount
        else:
            total_debit += txn.amount

        table_data.append([
            txn.created_at.strftime('%d/%m/%y'),
            txn.transaction_id[:16] + '...' if len(txn.transaction_id) > 16 else txn.transaction_id,
            (txn.description or '—')[:30],
            txn.category.title(),
            txn.transaction_type.upper(),
            amount_str,
            f"₹{txn.balance_after:,.2f}" if txn.balance_after else '—',
        ])

    # Summary row
    table_data.append(['', '', '', 'TOTAL CREDITS', '', f"₹{total_credit:,.2f}", ''])
    table_data.append(['', '', '', 'TOTAL DEBITS', '', f"₹{total_debit:,.2f}", ''])
    table_data.append(['', '', '', 'NET SAVINGS', '', f"₹{total_credit - total_debit:,.2f}", ''])

    col_widths = [1.8*cm, 3.5*cm, 4.5*cm, 2.5*cm, 2*cm, 2.7*cm, 2.5*cm]
    txn_table = Table(table_data, colWidths=col_widths, repeatRows=1)

    row_colors = []
    for i in range(1, len(table_data) - 3):
        txn = transactions[i - 1]
        if txn.transaction_type == 'credit':
            row_colors.append(('TEXTCOLOR', (5, i), (5, i), GREEN))
        else:
            row_colors.append(('TEXTCOLOR', (5, i), (5, i), RED))

    txn_table.setStyle(TableStyle([
        # Header
        ('BACKGROUND', (0, 0), (-1, 0), NAVY),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
        ('ROWBACKGROUNDS', (0, 1), (-1, -4), [colors.white, LIGHT_GRAY]),
        ('BACKGROUND', (0, -3), (-1, -1), colors.HexColor('#f0f4ff')),
        ('FONTNAME', (0, -3), (-1, -1), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0, 0), (-1, -1), 5),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        *row_colors
    ]))

    story.append(txn_table)
    story.append(Spacer(1, 1*cm))

    # Footer
    story.append(HRFlowable(width="100%", thickness=1, color=LIGHT_GRAY))
    story.append(Spacer(1, 0.3*cm))
    footer_style = ParagraphStyle(
        'Footer', parent=styles['Normal'],
        fontSize=7, textColor=GRAY, alignment=TA_CENTER
    )
    story.append(Paragraph(
        f"Generated on {utc_now().strftime('%d %B %Y at %I:%M %p UTC')} | "
        "NexaBank Demo — This is NOT a real bank statement.",
        footer_style
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
